    public void tablaorigin() {
    Code code = new Code();
    code.cargarImagenes();
    code.llenarVector();

    PanelTablero tablero = new PanelTablero();
    tablero.setOpaque(false); // ← Hacemos el panel transparente
    tablero.PTSelec(Code.imagenestablero);

    this.setLayout(new java.awt.BorderLayout());

    JPanel surCentro = new JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.CENTER, 0, 15));
    surCentro.setOpaque(false); // ← También transparente
    surCentro.add(tablero);

    this.add(surCentro, java.awt.BorderLayout.SOUTH);
}

    
    public void tablarepite() {
    PanelTablero tablero = new PanelTablero();
    tablero.setOpaque(false); // ← también aquí
    tablero.PTJuego(Code.imagenestablero);

    this.setLayout(new java.awt.BorderLayout());

    JPanel surIzquierda = new JPanel(new java.awt.FlowLayout(java.awt.FlowLayout.LEFT, 0, 0));
    surIzquierda.setOpaque(false); // ← importante
    surIzquierda.add(tablero);

    this.add(surIzquierda, java.awt.BorderLayout.SOUTH);
}

